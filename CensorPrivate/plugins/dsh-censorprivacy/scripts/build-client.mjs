// No transpiler is needed: the source uses the React platform API directly.
// Emit the same closure-factory contract as DSH's first-party web plugins.
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { Script } from 'node:vm';
const root = new URL('../', import.meta.url);
const { name } = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));
const source = await readFile(new URL('src/client.cjs', root), 'utf8');
const output = `// Generated by scripts/build-client.mjs; edit src/client.cjs.\nwindow.__ModuleLoader__.load({id:${JSON.stringify(name)},factory:(require)=>{\nconst module={exports:{}};const exports=module.exports;\n${source}\nreturn module.exports;\n}});\n`;
new Script(output, { filename: 'client.js' });
if (process.argv.includes('--check')) {
  if (await readFile(new URL('lib/client.js', root), 'utf8') !== output) throw new Error('Run npm run build in plugins/dsh-censorprivacy');
  console.log('DSH privacy client bundle is current');
  process.exit(0);
}
await mkdir(new URL('lib/', root), { recursive: true });
await writeFile(new URL('lib/client.js', root), output);
console.log('Built dsh-censorprivacy/lib/client.js');
